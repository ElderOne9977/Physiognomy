            # 23. High-level proportional relationships
            # ====================================================

            record[
                'nose_to_mouth_width_ratio'
            ] = safe_ratio(
                nose_width,
                mouth_width
            )


            record[
                'forehead_to_face_width_ratio'
            ] = safe_ratio(
                forehead_width,
                face_width_aligned
            )


            record[
                'chin_to_face_width_ratio'
            ] = safe_ratio(
                chin_width,
                face_width_aligned
            )


            record[
                'mouth_to_face_width_ratio'
            ] = safe_ratio(
                mouth_width,
                face_width_aligned
            )


            record[
                'eye_distance_to_face_width_ratio'
            ] = safe_ratio(
                inter_eye_distance,
                face_width_aligned
            )


            # ====================================================
            # 24. Save TXT
            # ====================================================

            try:

                write_txt(
                    out_txt_path,
                    record,
                    region_records,
                    kps5,
                    lm106
                )


            except Exception as e:

                stats['save_error'] += 1

                log_error(
                    img_path,
                    'save_txt',
                    e
                )

                continue


            # ====================================================
            # 25. Save record
            # ====================================================

            records.append(
                record
            )


            stats[
                'accepted_1_face'
            ] += 1


            if not qc['qc_pass']:

                stats[
                    'accepted_qc_warn'
                ] += 1


